"""t3 · menú público unificado (como Cannabismatica): catálogo al frente, tarjeta modelo del Club, mapa, reseñas,
redes, información legal, política de privacidad y Botón de arrepentimiento (apagado por defecto)."""
from h2 import *
t=T('t3 menú público: club, mapa, reseñas, redes, legal y arrepentimiento')
def sections(pg):return pg.evaluate("Array.from(document.querySelectorAll('section.psec')).map(s=>s.id)")
with sync_playwright() as p:
    b,c,pg=launch(p)
    pg.goto(HTML);pg.wait_for_timeout(600)
    if pg.query_selector('[data-a=ageYes]'):pg.click('[data-a=ageYes]');pg.wait_for_timeout(300)
    s=sections(pg)
    t.chk(s[:2]==['sec_cat','sec_club'],'catálogo primero y después el Club: '+str(s))
    t.chk(s[-2:]==['sec_legal','sec_info'],'al final información legal y ubicación/reseñas/redes: '+str(s))
    club=pg.inner_text('#sec_club')
    t.chk('modelo' in club and 'Así se ve tu tarjeta' in club,'tarjeta del Club rotulada «modelo»')
    t.chk(pg.evaluate("document.querySelectorAll('#sec_club .cd').length")==10,'la tarjeta muestra la meta de 10 sellos')
    lg=pg.inner_text('#sec_legal')
    t.chk(all(x in lg for x in ['Privacidad','Donaciones voluntarias','REPROCANN','Mayoría de edad','Club de socios']),'textos legales plegables')
    t.chk('arrepentimiento' not in lg.lower() and not pg.query_selector('#arrepBtn'),'Botón de arrepentimiento apagado por defecto')
    t.chk(pg.query_selector('#sec_legal a[href="privacidad.html"]') is not None and pg.query_selector('.pfoot a[href="privacidad.html"]') is not None,'enlace a la política de privacidad en legal y en el pie')
    inf=pg.inner_text('#sec_info')
    t.chk('Dónde estamos' in inf and 'Cómo llegar' in inf,'panel de ubicación con «Cómo llegar»')
    t.chk('Dejar mi reseña' in inf,'panel de reseñas (sin reseñas inventadas)')
    soc=pg.evaluate("Array.from(document.querySelectorAll('#sec_info .socg a')).map(a=>[a.innerText.split('\\n')[0],a.getAttribute('href')])")
    t.chk(any(x[0]=='Instagram' and x[1].startswith('https://www.instagram.com/') for x in soc) and any(x[0]=='WhatsApp' for x in soc),'redes con ícono, nombre y enlace: '+str(soc))
    t.chk(not pg.query_selector('#mapbox iframe'),'el mapa no se carga hasta pedirlo')
    pg.click('[data-a=mapShow]');pg.wait_for_timeout(300)
    src=pg.evaluate("(document.querySelector('#mapbox iframe')||{}).src||''")
    t.chk(src.startswith('https://www.google.com/maps?q='),'mapa de Google al tocar «Ver el mapa»')
    # administración: encender el botón de arrepentimiento, redes y reseñas
    boot_admin(pg)
    go(pg,'#/panel/menupub');pg.wait_for_selector('#bk_arrep')
    t.chk(not pg.is_checked('#bk_arrep'),'interruptor de arrepentimiento apagado')
    pg.check('#bk_arrep');pg.wait_for_timeout(300)
    t.chk(st(pg,"S.menuCfg.arrep===true&&S.audit.some(a=>a.a==='menu_arrepentimiento')"),'encenderlo queda guardado y auditado')
    go(pg,'#/panel/admin');pg.wait_for_selector('#o_tt')
    pg.fill('#o_tt','terps.salta');pg.fill('#o_rv','javascript:alert(1)');pg.click('[data-a=orgSave]');pg.wait_for_timeout(300)
    t.chk('https' in toast(pg),'enlace de reseñas que no es https: rechazado')
    pg.fill('#o_rv','https://g.page/r/ejemplo-resena');pg.click('[data-a=orgSave]');pg.wait_for_timeout(300)
    t.chk(st(pg,"S.org.tiktok")=='terps.salta' and st(pg,"S.org.reviewUrl").startswith('https://'),'TikTok y enlace de reseñas guardados')
    pg.evaluate("location.hash='#/'");pg.wait_for_timeout(500)
    if pg.query_selector('[data-a=ageYes]'):pg.click('[data-a=ageYes]');pg.wait_for_timeout(300)
    lg=pg.inner_text('#sec_legal')
    t.chk('arrepentimiento' in lg.lower(),'con el interruptor encendido aparece el texto de arrepentimiento')
    href=pg.evaluate("(document.querySelector('#arrepBtn')||{}).href||''")
    t.chk(href.startswith('https://wa.me/5493875140655') and 'arrepentimiento' in href.lower(),'el botón abre WhatsApp de la organización con el pedido redactado')
    rv=pg.evaluate("Array.from(document.querySelectorAll('#sec_info a')).map(a=>a.textContent+'|'+a.getAttribute('href'))")
    t.chk(any(x.startswith('Dejar mi reseña') and 'g.page/r/' in x for x in rv) and any(x.startswith('Ver reseñas') for x in rv),'«Dejar mi reseña» con el enlace cargado y «Ver reseñas»: '+str(rv))
    t.chk(any('tiktok.com/@terps.salta' in (a or '') for a in pg.evaluate("Array.from(document.querySelectorAll('.socg a')).map(a=>a.href)")),'TikTok aparece en redes')
    # forma: 360 px sin desbordes, botones táctiles
    pg.set_viewport_size({'width':360,'height':800});pg.wait_for_timeout(300)
    t.chk(pg.evaluate("document.documentElement.scrollWidth<=362"),'360 px sin desborde horizontal ('+str(pg.evaluate('document.documentElement.scrollWidth'))+')')
    small=pg.evaluate("Array.from(document.querySelectorAll('#sec_info .socg a,#arrepBtn,#sec_info .btn')).filter(e=>e.getBoundingClientRect().height<44).map(e=>e.textContent.trim().slice(0,20))")
    t.chk(not small,'botones de los paneles de al menos 44 px: '+str(small))
    errs=[e for e in pg.errs if 'Failed to load resource' not in e]
    t.chk(not errs,'sin errores de consola: '+str(errs[:3]))
    b.close()
sys.exit(0 if t.done() else 1)
